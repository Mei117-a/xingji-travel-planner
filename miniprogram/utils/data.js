const FAV_KEY = 'xingji-favs-v1';

function getFavs() {
  try {
    const raw = wx.getStorageSync(FAV_KEY);
    if (Array.isArray(raw)) return raw;
  } catch (e) { /* 忽略 */ }
  return [];
}

function isFav(key) { return getFavs().indexOf(key) > -1; }

function toggleFav(key) {
  const list = getFavs();
  const i = list.indexOf(key);
  if (i > -1) list.splice(i, 1); else list.unshift(key);
  try { wx.setStorageSync(FAV_KEY, list); } catch (e) { /* 忽略 */ }
  return i === -1; // true = 已收藏
}

